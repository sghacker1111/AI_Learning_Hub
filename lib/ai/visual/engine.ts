export function generateEducationalVisual(prompt: string): EducationalVisual {
  const normalized = prompt.toLowerCase();
  const title = shortTitle(prompt);
  const classification = classifyAIRequest(prompt);
  let kind: EducationalVisualKind;
  let rendered: { svg: string; alt: string };

  if (/venn|set|union|intersection|survey/.test(normalized)) {
    kind = "VENN_DIAGRAM";
    rendered = vennVisual(title);
  } else if (/water cycle|evaporation|condensation|precipitation/.test(normalized)) {
    kind = "WATER_CYCLE";
    rendered = waterCycleVisual(title);
  } else if (/force|pressure|upthrust|buoy|archimedes|density/.test(normalized)) {
    kind = "FORCE_DIAGRAM";
    rendered = forceVisual(title);
  } else {
    kind = "CONCEPT_MAP";
    rendered = conceptMapVisual(title);
  }

  return {
    kind,
    imageDataUrl: toDataUrl(rendered.svg),
    alt: rendered.alt,
    width: WIDTH,
    height: HEIGHT,
    classification,
    generatedBy: "deterministic-visual-engine",
  };
}
