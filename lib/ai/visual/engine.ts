import { classifyAIRequest, type AIRequestClassification } from "../classifier";

export type EducationalVisualKind = "VENN_DIAGRAM" | "WATER_CYCLE" | "FORCE_DIAGRAM" | "CONCEPT_MAP";

export interface EducationalVisual {
  kind: EducationalVisualKind;
  imageDataUrl: string;
  alt: string;
  width: number;
  height: number;
  classification: AIRequestClassification;
  generatedBy: "deterministic-visual-engine";
}

const WIDTH = 960;
const HEIGHT = 600;

function escapeXml(value: string): string {
  return value
    .replace(/[\u0000-\u001f\u007f]/g, " ")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

function shortTitle(value: string): string {
  const oneLine = value.replace(/\s+/g, " ").trim();
  return escapeXml(oneLine.length > 72 ? `${oneLine.slice(0, 69)}...` : oneLine || "Educational visual");
}

